const tables: Record<Lang, Record<Key, string>> = { ko, en };
let lang: Lang = 'ko';

export function setLang(l: Lang): void {
  lang = l;
}

export function getLang(): Lang {
  return lang;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return (tables[lang][key] ?? ko[key]).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}
